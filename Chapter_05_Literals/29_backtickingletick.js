// String literal examples: backticks, single quotes, and double quotes

// Backticks allow template literals, interpolation, and multiline strings
const name = 'Alice';
const greeting = `Hello, ${name}! Welcome to JavaScript.`;
console.log('backtick string:', greeting);

// Single quotes are a standard string delimiter
const singleQuote = 'This is a string in single quotes.';
console.log('single quote string:', singleQuote);

// Double quotes are another standard string delimiter
const doubleQuote = "This is a string in double quotes.";
console.log('double quote string:', doubleQuote);
